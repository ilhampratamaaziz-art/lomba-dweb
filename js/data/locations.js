export function getLocationById(id) {
  return LOCATIONS.find(loc => loc.id === id) || LOCATIONS[0]; // default Jakarta Pusat
}

export function getLocationsByRegion(region) {
  if (region === 'all') return LOCATIONS;
  return LOCATIONS.filter(loc => loc.region.toLowerCase().includes(region.toLowerCase()));
}

export function findLocationByQuery(query) {
  const q = query.toLowerCase().trim();
  return LOCATIONS.find(loc => 
    loc.name.toLowerCase().includes(q) || 
    loc.province.toLowerCase().includes(q) ||
    (loc.desa && loc.desa.toLowerCase().includes(q))
  );
}
